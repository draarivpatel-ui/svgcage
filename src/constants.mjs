export function svgcageSeverityForCode(code) {
  if (CRITICAL_CODES.has(code)) return SEVERITY.CRITICAL;
  if (HIGH_CODES.has(code)) return SEVERITY.HIGH;
  if (LOW_CODES.has(code)) return SEVERITY.LOW;
  return SEVERITY.MEDIUM;
}

